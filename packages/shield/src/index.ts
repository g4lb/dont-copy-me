export interface ShieldOptions {
  blockTraining: boolean;
  blockSearch: boolean;
  blockUserAgents: boolean;
}

export function shieldOptionsFromConfig(waf: DcmConfig['waf']): ShieldOptions {
  return {
    blockTraining: waf.blockAiTrainingCrawlers,
    blockSearch: !waf.allowSearchEngines,
    blockUserAgents: false,
  };
}

export function selectCrawlers(options: ShieldOptions): CrawlerInfo[] {
  return AI_CRAWLERS.filter(
    (c) =>
      (c.purpose === 'training' && options.blockTraining) ||
      (c.purpose === 'search' && options.blockSearch) ||
      (c.purpose === 'user-agent' && options.blockUserAgents),
  );
}

export function robotsTxt(options: ShieldOptions): string {
  const blocked = selectCrawlers(options);
  const lines = [
    '# Generated by Don\'t Copy Me (dcm shield).',
    '# robots.txt is ADVISORY: well-behaved crawlers honor it, others ignore it. It is not access control.',
    '',
  ];
  for (const crawler of blocked) {
    lines.push(`# ${crawler.operator} (${crawler.purpose})`, `User-agent: ${crawler.token}`, 'Disallow: /', '');
  }
  lines.push('# Everyone else, including search engines and accessibility tools, keeps normal access.', 'User-agent: *', 'Allow: /', '');
  return lines.join('\n');
}

/** Double-quoted string with backslashes and quotes escaped (Cloudflare expressions, nginx values). */
function quoted(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** Cloudflare Rulesets API payload. It is a template: dcm never calls the Cloudflare API. */
export function cloudflareRules(options: ShieldOptions): Record<string, unknown> {
  const blocked = selectCrawlers(options);
  const uaExpr = blocked.map((c) => `(http.user_agent contains ${quoted(c.token)})`).join(' or ');
  const rules: Array<Record<string, unknown>> = [];
  if (uaExpr) {
    rules.push({
      description: 'dcm: block declared AI crawlers (user-agent based, spoofable)',
      expression: uaExpr,
      action: 'block',
    });
  }
  if (options.blockTraining) {
    rules.push({
      description: 'dcm: block verified bots in the AI Crawler category',
      expression: '(cf.verified_bot_category eq "AI Crawler")',
      action: 'block',
    });
  }
  return { custom_rules: { phase: 'http_request_firewall_custom', rules } };
}

export function nginxSnippet(options: ShieldOptions): string {
  const blocked = selectCrawlers(options);
  return [
    '# Generated by Don\'t Copy Me (dcm shield). Review before use; include inside the http {} block.',
    'map $http_user_agent $dcm_ai_crawler {',
    '    default 0;',
    ...blocked.map((c) => `    "~*${c.token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}" 1;`),
    '}',
    '',
    '# Inside your server {} block:',
    '# if ($dcm_ai_crawler) { return 403; }',
    '',
  ].join('\n');
}

export function shieldReadme(options: ShieldOptions, tdm?: TdmOptions): string {
  const blocked = selectCrawlers(options);
  const tdmRow = tdm ? '\n| tdm-headers.txt | TDMRep `tdm-reservation` / `tdm-policy` headers for `_headers`, nginx and vercel.json. A declaration, not a block. |' : '';
  return `# Don't Copy Me: rights-declaration templates

These files are **templates**. \`dcm shield\` never changes DNS, CDN, hosting or firewall settings.
Review each file and apply it yourself. They repeat the site's rights notice at the HTTP layer:
which AI crawlers you ask not to collect the site, and your text-and-data-mining reservation.

| File | Purpose |
|---|---|
| robots.txt | Asks ${blocked.length} declared AI crawlers not to crawl. Advisory only. |
| cloudflare-rules.json | Cloudflare Rulesets API payload that blocks the same declared AI crawlers. |
| nginx-ai-crawlers.conf | nginx user-agent map for the same crawlers. |${tdmRow}

## Limits you should know about

- **robots.txt is not access control.** Crawlers that ignore it are unaffected.
- **User-agent rules can be spoofed.** Agents that drive a real browser (Playwright, Chrome
  extensions, computer-use) send a normal browser user agent and pass these rules.
- **TDMRep headers declare a reservation;** they do not stop anyone from fetching the page.
- **Verified-bot categories** (\`cf.verified_bot_category\`) only cover bots that declare themselves.
- Keep search engines, accessibility tools, uptime monitors and your own CI on an allow-list.
`;
}

export interface TdmOptions {
  /** Policy URL sent as `tdm-policy` (usually your terms page). */
  policyUrl?: string;
}

/** Options for the TDMRep HTTP headers, or undefined when rights/tdmReservation are off. */
export function tdmOptionsFromConfig(rights: DcmConfig['rights']): TdmOptions | undefined {
  if (!rights.enabled || !rights.tdmReservation) return undefined;
  return rights.termsUrl ? { policyUrl: rights.termsUrl } : {};
}

/**
 * W3C TDMRep HTTP headers (`tdm-reservation`, `tdm-policy`) in the formats static hosts read:
 * `_headers` (Netlify, Cloudflare Pages), nginx and vercel.json. Same declaration as the meta tags
 * and `/.well-known/tdmrep.json` that `dcm protect` writes, sent on every response.
 */
export function tdmHeaders(tdm: TdmOptions): string {
  const headers: Array<[string, string]> = [['tdm-reservation', '1'], ...(tdm.policyUrl ? [['tdm-policy', tdm.policyUrl] as [string, string]] : [])];
  const vercel = { headers: [{ source: '/(.*)', headers: headers.map(([key, value]) => ({ key, value })) }] };
  return [
    "# Generated by Don't Copy Me (dcm shield). W3C TDMRep reservation headers.",
    '# A machine-readable rights declaration, not access control: it states your reservation,',
    '# it does not stop anyone from fetching the page.',
    '',
    '# --- _headers (Netlify, Cloudflare Pages) ---',
    '/*',
    ...headers.map(([k, v]) => `  ${k}: ${v}`),
    '',
    '# --- nginx (inside server {}) ---',
    ...headers.map(([k, v]) => `# add_header ${k} ${quoted(v)} always;`),
    '',
    '# --- vercel.json ---',
    ...JSON.stringify(vercel, null, 2).split('\n').map((l) => `# ${l}`),
    '',
  ].join('\n');
}

export interface ShieldFile {
  name: string;
  content: string;
}

export function generateShieldFiles(options: ShieldOptions, tdm?: TdmOptions): ShieldFile[] {
  return [
    { name: 'robots.txt', content: robotsTxt(options) },
    { name: 'cloudflare-rules.json', content: `${JSON.stringify(cloudflareRules(options), null, 2)}\n` },
    { name: 'nginx-ai-crawlers.conf', content: nginxSnippet(options) },
    ...(tdm ? [{ name: 'tdm-headers.txt', content: tdmHeaders(tdm) }] : []),
    { name: 'README.md', content: shieldReadme(options, tdm) },
  ];
}
